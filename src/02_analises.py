pares_correlacao = [
    ("atraso_calculado_min", "tempo_real_min"),
    ("atraso_calculado_min", "distancia_km"),
    ("atraso_calculado_min", "numero_paradas"),
    ("atraso_calculado_min", "velocidade_media_kmh"),
    ("atraso_calculado_min", "ocupacao_pct"),
    ("atraso_calculado_min", "consumo_energia_kwh"),
    ("passageiros_transportados", "consumo_energia_kwh"),
    ("distancia_km", "consumo_energia_kwh"),
    ("ocupacao_pct", "consumo_kwh_por_passageiro")
]

resultados_correlacao = []

for x, y in pares_correlacao:

    if x not in df.columns or y not in df.columns:
        continue

    dados = df[[x, y]].dropna()

    if len(dados) < 3:
        continue

    pearson_r, pearson_p = stats.pearsonr(
        dados[x],
        dados[y]
    )

    spearman_r, spearman_p = stats.spearmanr(
        dados[x],
        dados[y]
    )

    resultados_correlacao.append({
        "variavel_x": x,
        "variavel_y": y,
        "pearson_r": round(pearson_r, 4),
        "pearson_p": round(pearson_p, 6),
        "spearman_r": round(spearman_r, 4),
        "spearman_p": round(spearman_p, 6)
    })

correlacoes = pd.DataFrame(
    resultados_correlacao
)

