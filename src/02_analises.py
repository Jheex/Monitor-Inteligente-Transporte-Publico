# ============================================================
# 11. TESTE DE HIPÓTESE 1
#    CHUVA x ATRASO
#
# H0: a média de atraso é igual em dias com e sem chuva.
# H1: a média de atraso é diferente.
# ============================================================

print("\n" + "=" * 70)
print("11. TESTE DE HIPÓTESE - CHUVA x ATRASO")
print("=" * 70)

if {
    "chuva",
    "atraso_calculado_min"
}.issubset(df.columns):

    grupo_sem_chuva = (
        df.loc[
            df["chuva"] == "Não",
            "atraso_calculado_min"
        ]
        .dropna()
    )

    grupo_com_chuva = (
        df.loc[
            df["chuva"] == "Sim",
            "atraso_calculado_min"
        ]
        .dropna()
    )

    print("Média sem chuva:",
          round(grupo_sem_chuva.mean(), 2))

    print("Média com chuva:",
          round(grupo_com_chuva.mean(), 2))

    # Teste de Welch, adequado quando as variâncias podem diferir
    t_stat, p_valor = stats.ttest_ind(
        grupo_sem_chuva,
        grupo_com_chuva,
        equal_var=False
    )

    print("\nt =", round(t_stat, 4))
    print("p-valor =", round(p_valor, 6))

    if p_valor < ALPHA:
        print(
            "Conclusão: rejeitamos H0. "
            "Há evidência de diferença estatisticamente "
            "significativa entre os grupos."
        )
    else:
        print(
            "Conclusão: não rejeitamos H0. "
            "Não há evidência estatística suficiente "
            "de diferença entre os grupos."
        )


# ============================================================
# 12. TESTE DE HIPÓTESE 2
#     NÍVEL DE TRÁFEGO x ATRASO
#
# H0: as médias de atraso são iguais nos níveis de tráfego.
# H1: pelo menos um grupo apresenta média diferente.
# ============================================================

print("\n" + "=" * 70)
print("12. TESTE DE HIPÓTESE - TRÁFEGO x ATRASO")
print("=" * 70)

if {
    "nivel_trafego",
    "atraso_calculado_min"
}.issubset(df.columns):

    grupos_trafego = []

    for nivel in ["Baixo", "Moderado", "Alto"]:

        grupo = (
            df.loc[
                df["nivel_trafego"] == nivel,
                "atraso_calculado_min"
            ]
            .dropna()
        )

        print(
            f"Média de atraso - {nivel}: "
            f"{grupo.mean():.2f} min"
        )

        grupos_trafego.append(grupo)

    # ANOVA de uma via
    f_stat, p_valor_anova = stats.f_oneway(
        *grupos_trafego
    )

    print("\nF =", round(f_stat, 4))
    print("p-valor =", round(p_valor_anova, 6))

    if p_valor_anova < ALPHA:
        print(
            "Conclusão: rejeitamos H0. "
            "Existe diferença estatisticamente significativa "
            "entre pelo menos dois níveis de tráfego."
        )
    else:
        print(
            "Conclusão: não rejeitamos H0. "
            "Não foi identificada diferença estatística "
            "suficiente entre os níveis de tráfego."
        )


# ============================================================
# 13. TESTE DE HIPÓTESE 3
#     LINHAS COMPARADAS PELO ATRASO
#
# Uso: identificar linhas com comportamento diferente.
# Não testamos todas as linhas entre si; selecionamos
# as linhas com maior volume de viagens.
# ============================================================

print("\n" + "=" * 70)
